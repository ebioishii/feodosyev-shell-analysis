"""1D double-shell: strain sweep from a specified equilibrated initial state.

Requires interpolation.py and heat_then_pressurize.py next to this script.
Loads a physically admissible initial hoop strain and plastic history from
the JSON generated by heat_then_pressurize.py (or an equivalently validated
state JSON placed at that path). No heating is performed in this script.
"""

from __future__ import annotations

import json
from pathlib import Path

from interpolation import E_at, flow_stress, thermal_strain
from heat_then_pressurize import (
    OUTPUT_DIR,
    plot_history, automatic_strain_history, print_state,
    validate_geometry, validate_state, write_pressure_csv,
)


def read_initial_state_interactively() -> dict:
    """Load the recorded initial state; do not ask for numerical controls.

    Run heat_then_pressurize.py first, or place a previously known and
    validated initial-state JSON at the same output location.
    Geometry, temperature and plastic history MUST come from one state.
    """
    state_path = OUTPUT_DIR / "thermal_preload_state.json"
    print("\n=== 已知初始狀態：自動應變控制的雙筒模型 ===")
    if not state_path.is_file():
        raise FileNotFoundError(
            f"找不到已知初始狀態檔：{state_path}；"
            "請先執行 heat_then_pressurize.py，或提供符合格式的初始狀態 JSON。"
        )
    data = json.loads(state_path.read_text(encoding="utf-8"))
    if data.get("format") != "double_shell_initial_state_v1":
        raise ValueError("初始狀態 JSON 格式不符")
    fields = (
        "R_m", "h_i_m", "h_o_m", "T_i_C", "T_o_C",
        "p_start_Pa", "epsilon_theta0", "epsilon_p_i", "kappa_i",
        "epsilon_p_o", "kappa_o",
    )
    result = {name: float(data[name]) for name in fields}
    print(f"已載入 {state_path}")
    print(f"幾何：R={result['R_m']*1000:g} mm, "
          f"hi={result['h_i_m']*1000:g} mm, ho={result['h_o_m']*1000:g} mm")
    print(f"溫度：Ti={result['T_i_C']:g}°C, To={result['T_o_C']:g}°C")
    return result


def check_initial_equilibrium(data: dict) -> None:
    """Reject an initial state inconsistent with the prescribed p and material law."""
    R, hi, ho = data["R_m"], data["h_i_m"], data["h_o_m"]
    Ti, To = data["T_i_C"], data["T_o_C"]
    eps0, p0 = data["epsilon_theta0"], data["p_start_Pa"]
    validate_geometry(R, hi, ho)
    si = (data["epsilon_p_i"], data["kappa_i"])
    so = (data["epsilon_p_o"], data["kappa_o"])
    validate_state(Ti, si)
    validate_state(To, so)

    sigma_i = E_at(Ti) * (eps0 - thermal_strain(Ti) - si[0])
    sigma_o = E_at(To) * (eps0 - thermal_strain(To) - so[0])
    stress_tol = 1e-7 * max(abs(sigma_i), abs(sigma_o), 1e6)
    if abs(sigma_i) > flow_stress(Ti, si[1]) + stress_tol:
        raise ValueError("Inner 初始應力超出由 κi 決定的當前降伏範圍")
    if abs(sigma_o) > flow_stress(To, so[1]) + stress_tol:
        raise ValueError("Outer 初始應力超出由 κo 決定的當前降伏範圍")

    p_from_stress = (hi * sigma_i + ho * sigma_o) / R
    p_tol = max(100.0, 1e-5 * max(abs(p0), abs(p_from_stress)))
    if abs(p_from_stress - p0) > p_tol:
        raise ValueError(
            "指定初始狀態不滿足環向平衡："
            f"你輸入的 p0={p0/1e6:.6f} MPa；"
            f"由狀態算得 p={p_from_stress/1e6:.6f} MPa。"
            "請提供一致的 εθ0、εp、κ，或用前一程式輸出的 JSON。"
        )
    print(f"初始狀態驗證通過：σi={sigma_i/1e6:.4f} MPa, "
          f"σo={sigma_o/1e6:.4f} MPa, p0={p0/1e6:.4f} MPa")


def main() -> None:
    data = read_initial_state_interactively()
    check_initial_equilibrium(data)
    eps_start = data["epsilon_theta0"]
    print(f"\n目前初始總環向應變：{eps_start*100:.6f}%")
    history, stop_reason = automatic_strain_history(
        eps_start,
        data["T_i_C"], data["T_o_C"],
        data["R_m"], data["h_i_m"], data["h_o_m"],
        (data["epsilon_p_i"], data["kappa_i"]),
        (data["epsilon_p_o"], data["kappa_o"]),
    )
    print(f"自動取樣：{len(history)} 點；總環向應變 "
          f"{eps_start*100:.5f}% → {history[-1]['epsilon_theta']*100:.5f}%")
    print(f"停止原因：{stop_reason}")
    p_err = abs(history[0]["p_g"] - data["p_start_Pa"])
    p_tol = max(
        100.0, 1e-5 * max(abs(data["p_start_Pa"]), abs(history[0]["p_g"])))
    if p_err > p_tol:
        raise ArithmeticError("第一個應變點沒有重現指定的初始壓力")

    print("\n應變掃描終點：")
    print_state(history[-1])
    OUTPUT_DIR.mkdir(exist_ok=True)
    csv_path = OUTPUT_DIR / "known_initial_pg_strain.csv"
    png_path = OUTPUT_DIR / "known_initial_pg_strain.png"
    write_pressure_csv(history, csv_path)
    plot_history(
        history,
        "1D double-shell: pressurization from a known initial state",
        png_path,
    )
    print(f"\n曲線 CSV：{csv_path}")
    print(f"曲線圖片：{png_path}")
    print("注意：自動取樣終點不是失效或停止操作應變。")
    print("此處只有 Feodosyev 的應變控制順序及環向平衡；未計入軸向平衡等原文完整方程。")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, FileNotFoundError, ImportError, ArithmeticError) as err:
        print(f"\n計算無法完成：{err}")
        raise SystemExit(1) from err
